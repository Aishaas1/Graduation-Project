import {readFile} from 'node:fs/promises';
import {test,before,after} from 'node:test';
import {initializeTestEnvironment,assertFails,assertSucceeds} from '@firebase/rules-unit-testing';
import {doc,setDoc,getDoc,updateDoc} from 'firebase/firestore';
import {ref,uploadBytes,getBytes} from 'firebase/storage';
let env;
before(async()=>{env=await initializeTestEnvironment({projectId:'demo-dhamar',firestore:{rules:await readFile('firestore.rules','utf8')},storage:{rules:await readFile('storage.rules','utf8')}});});
after(async()=>{await env.cleanup();});
const data={ownerId:'citizen',ownerName:'أحمد',title:'عنوان',description:'وصف',category:'طرق',district:'ذمار',accused:'',employer:'',accusedPhone:'',created:new Date().toISOString(),status:'جديدة',attachments:[]};
test('ownership, role escalation, messages, attachments and status permissions',async()=>{
  const owner=env.authenticatedContext('citizen',{email:'a@example.com'});
  const other=env.authenticatedContext('other',{email:'b@example.com'});
  const admin=env.authenticatedContext('admin',{email:'admin@example.com',admin:true});
  await assertSucceeds(setDoc(doc(owner.firestore(),'users/citizen'),{name:'أحمد',email:'a@example.com',phone:'777123456'}));
  await assertFails(updateDoc(doc(owner.firestore(),'users/citizen'),{admin:true}));
  await assertSucceeds(setDoc(doc(admin.firestore(),'users/admin'),{name:'المدير',email:'admin@example.com',phone:'777123456'}));
  await assertSucceeds(setDoc(doc(owner.firestore(),'complaints/one'),data));
  await assertFails(getDoc(doc(other.firestore(),'complaints/one')));
  await assertFails(getDoc(doc(env.unauthenticatedContext().firestore(),'complaints/one')));
  await assertFails(updateDoc(doc(owner.firestore(),'complaints/one'),{status:'تم الحل'}));
  await assertSucceeds(getDoc(doc(admin.firestore(),'complaints/one')));
  await assertFails(setDoc(doc(other.firestore(),'complaints/one/messages/m'),{author:'x',text:'x',senderId:'other',time:'2026',event:false}));
  await assertFails(setDoc(doc(owner.firestore(),'complaints/one/messages/spoof'),{author:'الإدارة',text:'x',senderId:'admin',time:'2026',event:true}));
  await assertSucceeds(setDoc(doc(owner.firestore(),'complaints/one/messages/ok'),{author:'أحمد',text:'متابعة',senderId:'citizen',time:'2026',event:false}));
  await assertSucceeds(uploadBytes(ref(owner.storage(),'complaints/citizen/one/a.pdf'),new Uint8Array([1,2,3]),{contentType:'application/pdf'}));
  await assertFails(uploadBytes(ref(other.storage(),'complaints/citizen/one/b.pdf'),new Uint8Array([1]),{contentType:'application/pdf'}));
  await assertFails(uploadBytes(ref(owner.storage(),'complaints/citizen/one/a.exe'),new Uint8Array([1]),{contentType:'application/octet-stream'}));
  await assertFails(getBytes(ref(other.storage(),'complaints/citizen/one/a.pdf')));
  await assertSucceeds(updateDoc(doc(owner.firestore(),'complaints/one'),{attachments:[{name:'a.pdf',path:'complaints/citizen/one/a.pdf',url:''}]}));
  await assertSucceeds(setDoc(doc(admin.firestore(),'complaints/one/messages/reply'),{author:'المدير',text:'تمت المعالجة',senderId:'admin',time:'2026',event:true}));
  await assertSucceeds(updateDoc(doc(admin.firestore(),'complaints/one'),{status:'تم الحل'}));
  await assertFails(updateDoc(doc(admin.firestore(),'complaints/one'),{ownerId:'admin'}));
});
